// Helper: get a site by id
export const getSiteById = (id: string): ConstructionSite | undefined =>
  MOCK_SITES.find((s) => s.id === id);

// Helper: get all jobs flat
export const getAllJobs = (): (Job & { siteName: string; siteAddress: string })[] =>
  MOCK_SITES.flatMap((site) =>
    site.jobs.map((job) => ({
      ...job,
      siteName: site.name,
      siteAddress: site.address,
    })),
  );

// Helper: availability color
export const getSiteAvailabilityStatus = (
  site: ConstructionSite,
): 'available' | 'limited' | 'full' => {
  const allFull = site.jobs.every((j) => j.filledCount >= j.headcount);
  if (allFull) return 'full';
  const almostFull = site.jobs.some(
    (j) => j.headcount > 0 && j.filledCount / j.headcount >= 0.7,
  );
  if (almostFull) return 'limited';
  return 'available';
};
